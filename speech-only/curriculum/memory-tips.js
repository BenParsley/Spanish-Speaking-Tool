export function getPhraseMemoryTip(item) {
  if (!item || typeof item !== 'object') return '';
  if (PHRASE_MEMORY_TIPS[item.id]) return PHRASE_MEMORY_TIPS[item.id];
  return item.note || '';
}

export function getNumberMemoryTip(num, ctx = null) {
  const n = Number(num);
  const mode = ctx?.isContext ? (ctx.resolvedMode || '') : '';
  if (mode === 'time') {
    return n === 1
      ? "1:00 is a lone wolf: singular 'es la UNA' (never 'son las')!"
      : "2:00–12:00 travel in packs: plural 'son las' + hour ('y cuarto' = :15, 'y media' = :30)!";
  }
  if (mode === 'prices') {
    return n === 1
      ? "Chop the '-o' off 'uno' before money: 'UN dólar'!"
      : "Say the number + masculine 'dólares' (numbers ending in 1 chop to '-ún', like 'veintiún dólares')!";
  }
  if (mode === 'age') {
    if (ctx?.isQuantity) {
      if (ctx.quantityNounEn && ctx.quantityNounEs) {
        const genderHint =
          ctx.quantityGender === 'f'
            ? 'feminine — use "una / veintiuna" for numbers ending in 1'
            : 'masculine — use "un / veintiún" for numbers ending in 1';
        return `"${ctx.quantityNounEn}" = "${ctx.quantityNounEs}" (${genderHint})!`;
      }
      return "Match numbers ending in 1 to the noun's gender: 'un / veintiún' for masculine (minutos, días, boletos) and 'una / veintiuna' for feminine (personas, horas, empanadas)!";
    }
    return "In Spanish you COLLECT your years like trophies: 'tengo' + number + 'años'!";
  }
  if (NUMBER_BASE_TIPS[n]) return NUMBER_BASE_TIPS[n];
  if (n > 20 && n < 30) {
    const unit = n % 10;
    return `Superglue rule for 21–29: fuse 'veinti-' (20) + '${unit}' into ONE unstoppable word!`;
  }
  if (n > 30 && n < 100) {
    const tens = Math.floor(n / 10) * 10;
    const ones = n % 10;
    return `3-piece Lego combo: ${tens} + 'y' (and) + ${ones} — snap them straight together!`;
  }
  if (n > 100 && n < 1000) {
    return "Hundreds snap together as 'ciento' (101–199) or '[digit]-cientos' (watch rebels 500 quinientos, 700 setecientos, 900 novecientos)!";
  }
  return "Read big numbers like a domino chain left-to-right: thousands ('mil') + hundreds + tens + 'y' + ones!";
}
